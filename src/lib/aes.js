const RSBOX = new Uint8Array(256);
for (let i = 0; i < 256; i++) RSBOX[SBOX[i]] = i;

const RCON = [0x01,0x02,0x04,0x08,0x10,0x20,0x40,0x80,0x1b,0x36];

function keyExpansion128(key) {
  const Nk = 4, Nr = 10;
  const w = new Uint8Array(16 * (Nr + 1));
  w.set(key, 0);

  let temp = new Uint8Array(4);
  for (let i = Nk; i < 4 * (Nr + 1); i++) {
    temp[0] = w[(i - 1) * 4 + 0];
    temp[1] = w[(i - 1) * 4 + 1];
    temp[2] = w[(i - 1) * 4 + 2];
    temp[3] = w[(i - 1) * 4 + 3];

    if (i % Nk === 0) {
      const t0 = temp[0];
      temp[0] = SBOX[temp[1]] ^ RCON[i / Nk - 1];
      temp[1] = SBOX[temp[2]];
      temp[2] = SBOX[temp[3]];
      temp[3] = SBOX[t0];
    }

    w[i * 4 + 0] = w[(i - Nk) * 4 + 0] ^ temp[0];
    w[i * 4 + 1] = w[(i - Nk) * 4 + 1] ^ temp[1];
    w[i * 4 + 2] = w[(i - Nk) * 4 + 2] ^ temp[2];
    w[i * 4 + 3] = w[(i - Nk) * 4 + 3] ^ temp[3];
  }

  return w;
}

function xtime(a) {
  return ((a << 1) ^ ((a & 0x80) ? 0x1b : 0x00)) & 0xff;
}

function mul(a, b) {
  let p = 0;
  for (let i = 0; i < 8; i++) {
    if (b & 1) p ^= a;
    const hi = a & 0x80;
    a = (a << 1) & 0xff;
    if (hi) a ^= 0x1b;
    b >>= 1;
  }
  return p & 0xff;
}

function addRoundKey(state, w, round) {
  for (let i = 0; i < 16; i++) state[i] ^= w[round * 16 + i];
}

function invSubBytes(state) {
  for (let i = 0; i < 16; i++) state[i] = RSBOX[state[i]];
}

function invShiftRows(state) {
  const s = state.slice();
  state[1] = s[13]; state[5] = s[1]; state[9] = s[5]; state[13] = s[9];
  state[2] = s[10]; state[6] = s[14]; state[10] = s[2]; state[14] = s[6];
  state[3] = s[7]; state[7] = s[11]; state[11] = s[15]; state[15] = s[3];
}

function invMixColumns(state) {
  for (let c = 0; c < 4; c++) {
    const a0 = state[c * 4 + 0];
    const a1 = state[c * 4 + 1];
    const a2 = state[c * 4 + 2];
    const a3 = state[c * 4 + 3];

    state[c * 4 + 0] = mul(a0, 14) ^ mul(a1, 11) ^ mul(a2, 13) ^ mul(a3, 9);
    state[c * 4 + 1] = mul(a0, 9) ^ mul(a1, 14) ^ mul(a2, 11) ^ mul(a3, 13);
    state[c * 4 + 2] = mul(a0, 13) ^ mul(a1, 9) ^ mul(a2, 14) ^ mul(a3, 11);
    state[c * 4 + 3] = mul(a0, 11) ^ mul(a1, 13) ^ mul(a2, 9) ^ mul(a3, 14);
  }
}

function decryptBlock128(block, w) {
  const Nr = 10;
  const state = block.slice();

  addRoundKey(state, w, Nr);

  for (let round = Nr - 1; round >= 1; round--) {
    invShiftRows(state);
    invSubBytes(state);
    addRoundKey(state, w, round);
    invMixColumns(state);
  }

  invShiftRows(state);
  invSubBytes(state);
  addRoundKey(state, w, 0);

  return state;
}

export function aesCbcDecrypt(key, iv, ciphertext, { removePadding = true } = {}) {
  const w = keyExpansion128(key);
  const blocks = ciphertext.length / 16;
  const output = new Uint8Array(ciphertext.length);
  let prevBlock = iv;

  for (let i = 0; i < blocks; i++) {
    const block = ciphertext.subarray(i * 16, i * 16 + 16);
    const decrypted = decryptBlock128(block, w);
    for (let j = 0; j < 16; j++) output[i * 16 + j] = decrypted[j] ^ prevBlock[j];
    prevBlock = block;
  }

  if (removePadding && output.length > 0) {
    const pad = output[output.length - 1];
    if (pad > 0 && pad <= 16) return output.slice(0, output.length - pad);
  }

  return output;
}
